class Main {
    public static void main(String[] args) {
        printHello();
        printSpace();
        printWorld();
    }

    private static void printHello() {
        System.out.print("Hello");
    }

    private static void printWorld() {
        System.out.print("world!");
    }

    private static void printSpace() {
        System.out.print(" ");
    }
}
